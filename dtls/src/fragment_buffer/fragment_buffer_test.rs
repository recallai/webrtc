#[test]
fn test_fragment_buffer_overflow() -> Result<()> {
    let mut fragment_buffer = FragmentBuffer::new();

    fragment_buffer.push(&[
        0x16, 0xfe, 0xff, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0F, 0x03, 0x00,
        0x00, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0xfe, 0xff, 0x00,
    ])?;

    let big_buffer = vec![0; 2_000_000];
    let result = fragment_buffer.push(&big_buffer);

    assert!(
        result.is_err(),
        "Pushing a buffer of size 2MB should have caused FragmentBuffer::push to return an error"
    );

    Ok(())
}

/// Builds one DTLS handshake record carrying body[offset..offset+len] of a
/// handshake message whose total length is body.len().
fn handshake_fragment_record(
    typ: u8,
    msg_seq: u16,
    body: &[u8],
    offset: usize,
    len: usize,
) -> Vec<u8> {
    let total = body.len();
    let mut rec = vec![
        0x16, 0xfe, 0xfd, // handshake, DTLS 1.2
        0x00, 0x00, // epoch
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // sequence number
    ];
    let content_len = (HANDSHAKE_HEADER_LENGTH + len) as u16;
    rec.extend_from_slice(&content_len.to_be_bytes());
    rec.push(typ);
    rec.extend_from_slice(&(total as u32).to_be_bytes()[1..]);
    rec.extend_from_slice(&msg_seq.to_be_bytes());
    rec.extend_from_slice(&(offset as u32).to_be_bytes()[1..]);
    rec.extend_from_slice(&(len as u32).to_be_bytes()[1..]);
    rec.extend_from_slice(&body[offset..offset + len]);
    rec
}

fn reassembled(typ: u8, msg_seq: u16, body: &[u8]) -> Vec<u8> {
    let total = body.len();
    let mut out = vec![typ];
    out.extend_from_slice(&(total as u32).to_be_bytes()[1..]);
    out.extend_from_slice(&msg_seq.to_be_bytes());
    out.extend_from_slice(&[0, 0, 0]);
    out.extend_from_slice(&(total as u32).to_be_bytes()[1..]);
    out.extend_from_slice(body);
    out
}

fn test_body(n: usize) -> Vec<u8> {
    (0..n).map(|i| (i * 7) as u8).collect()
}

/// Observed against Microsoft Teams media relays (2026-10-01, ap-northeast-1):
/// flight 4 arrived as SH+Cert+SKE[0..311) with the SKE[311..329) tail lost,
/// then the relay retransmitted SKE as a single 329-byte fragment. The
/// retransmission must complete the message (RFC 6347 Section 4.2.3).
#[test]
fn test_fragment_buffer_retransmit_covers_partial_fragment() -> Result<()> {
    let body = test_body(329);
    let mut fb = FragmentBuffer::new();

    assert!(fb.push(&handshake_fragment_record(12, 0, &body, 0, 311))?);
    assert!(
        fb.pop().is_err(),
        "message must not pop while bytes are missing"
    );

    assert!(fb.push(&handshake_fragment_record(12, 0, &body, 0, 329))?);
    let (out, epoch) = fb.pop()?;
    assert_eq!(out, reassembled(12, 0, &body));
    assert_eq!(epoch, 0);
    assert!(fb.pop().is_err());
    assert_eq!(fb.size(), 0);
    Ok(())
}

/// Retransmission re-fragmented at different boundaries than the original.
#[test]
fn test_fragment_buffer_retransmit_with_different_boundaries() -> Result<()> {
    let body = test_body(700);
    let mut fb = FragmentBuffer::new();

    // Original: 256-byte fragments, the middle one is lost.
    assert!(fb.push(&handshake_fragment_record(11, 0, &body, 0, 256))?);
    assert!(fb.push(&handshake_fragment_record(11, 0, &body, 512, 188))?);
    assert!(fb.pop().is_err());

    // Retransmit: 300-byte fragments.
    assert!(fb.push(&handshake_fragment_record(11, 0, &body, 0, 300))?);
    assert!(fb.push(&handshake_fragment_record(11, 0, &body, 300, 300))?);
    assert!(fb.push(&handshake_fragment_record(11, 0, &body, 600, 100))?);

    let (out, _) = fb.pop()?;
    assert_eq!(out, reassembled(11, 0, &body));
    assert_eq!(fb.size(), 0);
    Ok(())
}

/// Overlapping, duplicated, out-of-order and strict-subset fragments.
#[test]
fn test_fragment_buffer_overlapping_fragments() -> Result<()> {
    let body = test_body(500);
    let mut fb = FragmentBuffer::new();
    for (off, len) in [
        (200, 100),
        (150, 100),
        (200, 100),
        (200, 50),
        (0, 250),
        (400, 100),
        (300, 150),
    ] {
        assert!(fb.push(&handshake_fragment_record(11, 0, &body, off, len))?);
    }
    let (out, _) = fb.pop()?;
    assert_eq!(out, reassembled(11, 0, &body));
    assert_eq!(fb.size(), 0);
    Ok(())
}

/// A fragment that lies outside the message, or disagrees with the message's
/// type/length, must not be admitted (it would corrupt reassembly) and must
/// not prevent the valid fragments from completing.
#[test]
fn test_fragment_buffer_rejects_inconsistent_fragments() -> Result<()> {
    let body = test_body(100);
    let mut fb = FragmentBuffer::new();

    assert!(fb.push(&handshake_fragment_record(11, 0, &body, 0, 60))?);

    // Claims [80, 130) of a 100-byte message.
    let mut bad = handshake_fragment_record(11, 0, &test_body(130), 80, 50);
    bad[14..17].copy_from_slice(&100u32.to_be_bytes()[1..]); // handshake length = 100
    assert!(fb.push(&bad)?);
    // Different handshake type for the same message sequence.
    assert!(fb.push(&handshake_fragment_record(2, 0, &body, 60, 40))?);
    // Different total length for the same message sequence.
    assert!(fb.push(&handshake_fragment_record(11, 0, &test_body(300), 60, 240))?);
    assert!(fb.pop().is_err());
    assert_eq!(fb.size(), 60);

    assert!(fb.push(&handshake_fragment_record(11, 0, &body, 60, 40))?);
    let (out, _) = fb.pop()?;
    assert_eq!(out, reassembled(11, 0, &body));
    Ok(())
}

